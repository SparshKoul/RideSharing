import React from 'react';
import { useNavigate } from 'react-router-dom';
import { Inbox, Plus, ArrowRight, ShieldCheck, Power } from 'lucide-react';
import { useRide } from '../../hooks/useRide';
import { useAuth } from '../../hooks/useAuth';
import RideCard from '../../components/RideCard';
import EmptyState from '../../components/EmptyState';

export default function RideRequestsPage() {
  const navigate = useNavigate();
  const { currentUser } = useAuth();
  const {
    pendingRequests,
    driverOnline,
    setDriverOnline,
    driverAcceptRide,
    driverRejectRide,
    createSampleRequest,
  } = useRide();

  const handleAccept = (rideId) => {
    const success = driverAcceptRide(rideId, currentUser);
    if (success) {
      navigate(`/driver/trip/${rideId}`);
    }
  };

  return (
    <div className="space-y-8">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-[#16123F] border border-[#3B38F5]/40 text-[#D4FF00] font-neo-mono text-[10.5px] font-bold uppercase tracking-wider mb-2">
            <Inbox size={12} className="text-[#D4FF00]" />
            <span>DISPATCH QUEUE</span>
          </div>
          <h1 className="font-neo-heading text-2xl sm:text-4xl font-black uppercase text-white tracking-tight">
            INCOMING RIDE REQUESTS
          </h1>
          <p className="font-neo-grotesk text-xs sm:text-sm text-[#A5A1CE]">
            Real-time ride requests generated by riders in your current browser application.
          </p>
        </div>

        <div className="flex items-center gap-3">
          <button
            type="button"
            onClick={createSampleRequest}
            className="px-4 py-2.5 rounded-xl border-2 border-[#08071E] bg-[#D4FF00] text-[#08071E] font-neo-heading text-xs font-black uppercase tracking-wider shadow-[2px_2px_0_#3B38F5] transition-all cursor-pointer"
          >
            + Create Sample Request
          </button>
        </div>
      </div>

      {/* Offline Warning Banner if Driver is offline */}
      {!driverOnline && (
        <div className="p-4 rounded-2xl bg-amber-500/20 border-2 border-amber-400 text-amber-300 font-neo-grotesk text-xs sm:text-sm flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div className="flex items-center gap-2.5">
            <Power size={18} className="text-amber-400 shrink-0" />
            <span>You are currently <strong>OFFLINE</strong>. You must go online to accept incoming dispatch requests.</span>
          </div>
          <button
            type="button"
            onClick={() => setDriverOnline(true)}
            className="px-4 py-1.5 rounded-xl bg-amber-400 text-[#08071E] font-neo-heading text-xs font-black uppercase shrink-0"
          >
            Switch Online Now
          </button>
        </div>
      )}

      {/* Requests Grid */}
      {driverOnline && pendingRequests.length > 0 ? (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {pendingRequests.map((req) => (
            <RideCard
              key={req.id}
              ride={req}
              isDriverView={true}
              onAccept={handleAccept}
              onReject={driverRejectRide}
            />
          ))}
        </div>
      ) : (
        <EmptyState
          title={driverOnline ? 'No Ride Requests Available' : "You're Offline"}
          description={
            driverOnline
              ? 'No pending passenger bookings right now. You can create a test sample request to immediately simulate an incoming passenger dispatch!'
              : 'Toggle your status to ONLINE in the top navigation or banner to view requests.'
          }
          actionLabel={driverOnline ? 'Generate Test Request' : 'Switch Online'}
          onAction={driverOnline ? createSampleRequest : () => setDriverOnline(true)}
          icon={Inbox}
        />
      )}
    </div>
  );
}
